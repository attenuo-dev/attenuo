"""Run the injection suite and write ``results/<date>.json`` and ``results/<date>.md``.

    ONBEHALF_BIN_DIR=/path/to/bins python3 evaluation/injection-suite/run.py

Options: ``--cases id,id`` or ``--suite name`` to run a subset, ``--arms direct,onbehalf`` to
skip arms, ``--date`` to name the output files, ``--out DIR``, ``--keep DIR`` to keep the
generated configs, logs and audit export. Exit status 1 if any onbehalf-arm call does not
match its expected outcome, if a denied call reached the upstream, or if the audit check fails.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import subprocess
import sys
from pathlib import Path
from typing import Any

import harness

STAGE_NOTE = {
    "capability": "the delegation token does not cover the call",
    "policy": "the suite's Cedar policy refuses it",
    "lease": "the session was revoked",
}


def _git(*args: str) -> str:
    try:
        return subprocess.run(
            ["git", *args], cwd=harness.ROOT, capture_output=True, text=True, check=True
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def _bin_version(path: Path) -> str:
    try:
        out = subprocess.run([str(path), "--version"], capture_output=True, text=True, timeout=10)
        return (out.stdout or out.stderr).strip().splitlines()[0]
    except (OSError, IndexError, subprocess.SubprocessError):
        return "unknown"


def select(
    suites: list[harness.Suite], cases: str | None, suite: str | None
) -> list[harness.Suite]:
    wanted = set(cases.split(",")) if cases else None
    out = []
    for s in suites:
        if suite and s.name != suite:
            continue
        s.cases = [c for c in s.cases if wanted is None or c.id in wanted]
        if s.cases:
            out.append(s)
    if wanted:
        missing = wanted - {c.id for s in out for c in s.cases}
        if missing:
            raise SystemExit(f"unknown case ids: {', '.join(sorted(missing))}")
    return out


def problems(doc: dict[str, Any]) -> list[str]:
    """Everything that should fail the run: unexpected outcomes, leaks past a deny, audit."""
    out = []
    for c in doc["calls"]:
        where = f"{c['arm']} {c['case']}#{c['index']} {c['tool']}"
        if c["arm"] == "onbehalf" and not c["as_expected"]:
            out.append(
                f"{where}: expected {c['expect']}/{c['expect_stage']}, "
                f"got {c['outcome']}/{c['reason']}"
            )
        if c["outcome"] == "deny" and c["reached_upstream"]:
            out.append(f"{where}: denied but reached the upstream")
        if c["arm"] != "onbehalf" and c["outcome"] == "error":
            out.append(f"{where}: upstream returned an error")
    for arm, a in doc["audit"].items():
        if a["decisions_unmatched"]:
            out.append(
                f"{arm}: {len(a['decisions_unmatched'])} decisions not found in the audit log"
            )
        if a["cli_verify_exit"] != 0 or a["offline_verify_exit"] != 0 or a["export_exit"] != 0:
            out.append(f"{arm}: audit verification failed")
    return out


def _pct(n: int, d: int) -> str:
    return f"{n}/{d} ({100 * n / d:.0f}%)" if d else "0/0"


def render_markdown(doc: dict[str, Any], date: str) -> str:
    rows = harness.summarise(doc)["rows"]
    by_arm: dict[str, list[dict[str, Any]]] = {}
    for r in rows:
        by_arm.setdefault(r["arm"], []).append(r)

    def total(arm: str) -> dict[str, Any]:
        t: dict[str, Any] = {"suite": "**all**"}
        for r in by_arm.get(arm, []):
            for k, v in r.items():
                if isinstance(v, int):
                    t[k] = t.get(k, 0) + v
        return t

    meta = doc["meta"]
    n_calls = sum(r["attack_calls"] + r["benign_calls"] for r in by_arm.get("onbehalf", []))
    L = [
        f"# Injection suite results, {date}",
        "",
        "Generated by `evaluation/injection-suite/run.py`; do not edit by hand. Method, corpus and "
        "limits: [README](../README.md). Summary: "
        "[docs/evaluation/injection-suite.md](../../../docs/evaluation/injection-suite.md).",
        "",
        f"- Repository HEAD when run: `{meta['commit']}`; binaries report {meta['server_version']}",
        f"- Cases: {doc['cases']} in {len(by_arm.get('onbehalf', []))} suites; "
        f"calls per arm: {n_calls}",
        "- Synthetic tool-call sequences, no LLM in the loop. Upstreams are echo servers.",
        "",
        "## onbehalf (attenuated tokens + suite Cedar policy + leases)",
        "",
        "| Suite | Cases | Attack calls | Blocked: capability | Blocked: policy | Blocked: lease "
        "| Allowed (false negatives) | Benign calls | Benign denied (false positives) |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in [*by_arm.get("onbehalf", []), total("onbehalf")]:
        L.append(
            f"| {r['suite']} | {r['cases']} | {r['attack_calls']} | {r['blocked_capability']} "
            f"| {r['blocked_policy']} | {r['blocked_lease']} | {r['attack_allowed']} "
            f"| {r['benign_calls']} | {r['benign_denied']} |"
        )
    t = total("onbehalf")
    blocked = t["attack_calls"] - t["attack_allowed"]
    L += [
        "",
        f"Attack calls blocked: {_pct(blocked, t['attack_calls'])}, "
        f"of which {t['blocked_lease']} only after a scripted revocation by the user. "
        f"Benign calls denied: {_pct(t['benign_denied'], t['benign_calls'])}. "
        f"Calls that did not match the corpus's expected outcome: {t['unexpected']}.",
        "",
        "## Scope-only tokens, per suite",
        "",
        "Same cases, tokens carry tool names only (argument constraints dropped), Cedar policy "
        "permits everything. This is what per-tool OAuth scopes would give.",
        "",
        "| Suite | Attack calls | Blocked: capability | Blocked: lease | Allowed | Benign denied |",
        "|---|---:|---:|---:|---:|---:|",
        *[
            f"| {r['suite']} | {r['attack_calls']} | {r['blocked_capability']} "
            f"| {r['blocked_lease']} | {r['attack_allowed']} | {r['benign_denied']} |"
            for r in [*by_arm.get("scope_only", []), total("scope_only")]
            if by_arm.get("scope_only")
        ],
        "",
        "## Arms compared",
        "",
        "| Arm | Attack calls allowed | Attack calls that reached the upstream "
        "| Benign calls denied |",
        "|---|---:|---:|---:|",
    ]
    names = {
        "direct": "No onbehalf (direct to upstream)",
        "scope_only": "Scope-only tokens (tool names, no argument constraints, permit-all policy)",
        "scope_constraints": "Tokens with argument constraints, permit-all policy",
        "policy_only": "Suite policy with the root token (no attenuation)",
        "onbehalf": "onbehalf full",
    }
    for arm in harness.ARMS:
        if arm not in by_arm:
            continue
        t = total(arm)
        allowed = t["attack_allowed"]
        L.append(
            f"| {names[arm]} | {_pct(allowed, t['attack_calls'])} "
            f"| {_pct(t['attack_reached_upstream'], t['attack_calls'])} "
            f"| {_pct(t['benign_denied'], t['benign_calls'])} |"
        )

    calls = [c for c in doc["calls"] if c["arm"] == "onbehalf"]
    cm = doc["case_meta"]
    fn = [c for c in calls if c["role"] == "attack" and c["outcome"] != "deny"]
    fp = [c for c in calls if c["role"] == "benign" and c["outcome"] == "deny"]
    L += ["", "## Attack calls onbehalf allowed", ""]
    if fn:
        L += ["| Case | Class | Call | Why it got through |", "|---|---|---|---|"]
        for c in fn:
            why = c["note"] or cm[c["case"]]["note"] or ""
            L.append(f"| {c['case']} | {cm[c['case']]['class']} | `{c['tool']}` | {why} |")
    else:
        L.append("None.")
    L += ["", "## Benign calls onbehalf denied", ""]
    if fp:
        L += ["| Case | Call | Reason | Why |", "|---|---|---|---|"]
        for c in fp:
            why = c["note"] or cm[c["case"]]["note"] or ""
            L.append(f"| {c['case']} | `{c['tool']}` | `{c['reason']}` | {why} |")
    else:
        L.append("None.")

    by_class: dict[str, list[int]] = {}
    case_attacks: dict[str, list[bool]] = {}
    for c in calls:
        if c["role"] == "attack":
            case_attacks.setdefault(c["case"], []).append(c["outcome"] == "deny")
    for cid, blocked in case_attacks.items():
        b = by_class.setdefault(cm[cid]["class"], [0, 0, 0, 0])
        b[0] += 1
        b[1] += int(all(blocked))
        b[2] += len(blocked)
        b[3] += sum(blocked)
    L += [
        "",
        "## By case class",
        "",
        "Class labels follow the evaluation plan, section 5.3, and are per case: S a tool-level "
        "scope separates the injected call from the task's calls, C an argument constraint in the "
        "token does, D the separating value is only known at run time (the suite policy may still "
        "catch it), N nothing in the token or the policy separates at least one injected call. "
        "N cases often contain further attack calls that are blocked. One coder (the author), no "
        "agreement check yet.",
        "",
        "| Class | Cases | Cases with every attack call blocked | Attack calls | Blocked |",
        "|---|---:|---:|---:|---:|",
    ]
    for k in harness.CLASSES:
        if k in by_class:
            n, full, calls_n, calls_b = by_class[k]
            L.append(f"| {k} | {n} | {_pct(full, n)} | {calls_n} | {_pct(calls_b, calls_n)} |")

    L += ["", "## Audit", ""]
    for arm, a in doc["audit"].items():
        L.append(
            f"- {arm}: {a['entries']} audit entries; {a['decisions_matched']} of "
            f"{a['decisions_matched'] + len(a['decisions_unmatched'])} call decisions found by id "
            f"with the same decision and reason; `onbehalf audit verify` exit "
            f"{a['cli_verify_exit']}, offline `audit verify --file` on the export exit "
            f"{a['offline_verify_exit']}."
        )
    probs = problems(doc)
    L += ["", "## Problems", ""]
    L += [f"- {p}" for p in probs] if probs else ["None."]
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--cases")
    ap.add_argument("--suite")
    ap.add_argument("--arms", default=",".join(harness.ARMS))
    ap.add_argument("--date", default=dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d"))
    ap.add_argument("--out", type=Path, default=harness.HERE / "results")
    ap.add_argument("--keep", type=Path)
    a = ap.parse_args()

    arms = tuple(x for x in a.arms.split(",") if x)
    if any(x not in harness.ARMS for x in arms):
        raise SystemExit(f"--arms takes {','.join(harness.ARMS)}")
    suites = select(harness.load_corpus(), a.cases, a.suite)
    doc = harness.run(suites, arms, keep=a.keep)
    bins = harness.find_binaries()
    doc = {
        "meta": {
            "date": a.date,
            "commit": _git("rev-parse", "--short", "HEAD"),
            "server_version": _bin_version(bins.server),
        },
        **doc,
        "summary": harness.summarise(doc),
    }
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / f"{a.date}.json").write_text(json.dumps(doc, indent=1, sort_keys=False) + "\n")
    md = render_markdown(doc, a.date)
    (a.out / f"{a.date}.md").write_text(md)
    print(md)
    probs = problems(doc)
    for p in probs:
        print("PROBLEM:", p, file=sys.stderr)
    return 1 if probs else 0


if __name__ == "__main__":
    sys.exit(main())
